# ==============================================================================
# SOS Abdichtung - Automated Google Apps Script Deployment (clasp)
# ==============================================================================
# Synchronizes shared modules, pushes both Website API (apps-script) and
# Admin SPA (admin-script), and deploys / updates Web App endpoints.
# ==============================================================================

$ErrorActionPreference = "Stop"

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "  SOS Abdichtung - Backend & Admin Cloud Deployment       " -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Cyan

# 1. Check Clasp Installation
if (-not (Get-Command "clasp" -ErrorAction SilentlyContinue)) {
    Write-Host "[!] Google clasp CLI not found. Installing @google/clasp globally..." -ForegroundColor Yellow
    npm install -g @google/clasp
}

# 2. Check Authentication
$clasprcPath = Join-Path $env:USERPROFILE ".clasprc.json"
if (-not (Test-Path $clasprcPath)) {
    Write-Host ""
    Write-Host "[1/4] Google Account Authentication Required" -ForegroundColor Yellow
    Write-Host "A browser window will open. Log in with your Google Workspace account." -ForegroundColor Gray
    clasp login
} else {
    Write-Host "[1/4] Authenticated with Google clasp (~/.clasprc.json found)." -ForegroundColor Green
}

# 3. Sync Shared Modules
$backendDir = $PSScriptRoot
$sharedFile = Join-Path $backendDir "shared\Shared.js"
$estimatorSrc = Join-Path $backendDir "apps-script\Estimator.js"
$appsDir    = Join-Path $backendDir "apps-script"
$adminDir   = Join-Path $backendDir "admin-script"

Write-Host "[2/4] Syncing Shared.js & Estimator.js to apps-script and admin-script..." -ForegroundColor Cyan
Copy-Item -Path $sharedFile -Destination (Join-Path $appsDir "Shared.js") -Force
Copy-Item -Path $sharedFile -Destination (Join-Path $adminDir "Shared.js") -Force
Copy-Item -Path $estimatorSrc -Destination (Join-Path $adminDir "Estimator.js") -Force

# 4. Deploy Website API (backend/apps-script)
Write-Host ""
Write-Host "[3/4] Deploying Website API (backend/apps-script)..." -ForegroundColor Cyan
Push-Location $appsDir
try {
    if (-not (Test-Path ".clasp.json")) {
        Write-Host "Creating new Google Sheet + bound Apps Script project 'SOS Abdichtung — Anfragen & Kalkulation'..." -ForegroundColor Yellow
        clasp create --type sheets --title "SOS Abdichtung — Anfragen & Kalkulation"
    }
    Write-Host "Pushing Website API files to Google Apps Script..." -ForegroundColor Gray
    clasp push --force

    Write-Host "Creating Web App deployment for Website API..." -ForegroundColor Gray
    $deployOut = clasp deploy --description "SOS Abdichtung Website API (Leads, Photos, Calendar, E-Sign, AI Chat)" 2>&1 | Out-String
    Write-Host $deployOut -ForegroundColor Green
} finally {
    Pop-Location
}

# 5. Deploy Admin Dashboard (backend/admin-script)
Write-Host ""
Write-Host "[4/4] Deploying Admin Portal (backend/admin-script)..." -ForegroundColor Cyan
Push-Location $adminDir
try {
    $appsClasp = Join-Path $appsDir ".clasp.json"
    if (Test-Path $appsClasp) {
        $claspJson = Get-Content $appsClasp | ConvertFrom-Json
        if ($claspJson.parentId) {
            $sheetId = if ($claspJson.parentId -is [array]) { $claspJson.parentId[0] } else { $claspJson.parentId }
            if ($sheetId) {
                $cfgContent = "/* Auto-generated by deploy-backend.ps1 */`nvar SHEET_ID = '$sheetId';`n"
                Set-Content -Path (Join-Path $adminDir "Config.js") -Value $cfgContent -Encoding UTF8
                Write-Host "Linked Admin Config.js to Google Sheet ID: $sheetId" -ForegroundColor Green
            }
        }
    }

    if (-not (Test-Path ".clasp.json")) {
        Write-Host "Creating standalone Apps Script project 'SOS Abdichtung — Admin Portal'..." -ForegroundColor Yellow
        clasp create --type webapp --title "SOS Abdichtung — Admin Portal"
    }
    Write-Host "Pushing Admin Portal files to Google Apps Script..." -ForegroundColor Gray
    clasp push --force

    Write-Host "Creating Web App deployment for Admin Portal..." -ForegroundColor Gray
    $adminDeployOut = clasp deploy --description "SOS Abdichtung Admin Portal (Leads, Drive, GoBD Belege, Kalender)" 2>&1 | Out-String
    Write-Host $adminDeployOut -ForegroundColor Green
} finally {
    Pop-Location
}

Write-Host ""
Write-Host "==========================================================" -ForegroundColor Green
Write-Host "  ALL DONE! Backend & Admin deployed to Google Cloud.     " -ForegroundColor Green
Write-Host "==========================================================" -ForegroundColor Green
